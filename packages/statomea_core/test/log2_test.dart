import 'dart:math' as math;

import 'package:statomea_core/statomea_core.dart';
import 'package:test/test.dart';

void main() {
  test('log2 correctement arrondi (références calculées à 80 chiffres)', () {
    const cases = [
      (1.0000001, 1.4426949695965583e-07),
      (0.99999, -1.4427022544056922e-05),
      (1.4142, 0.49998616442187416),
      (0.7072, -0.4998098201580177),
      (3.0, 1.584962500721156),
      (1e-300, -996.5784284662087),
      (7500000000000.0, 42.770027734256864),
      (0.1, -3.321928094887362),
      (1234.5678, 10.269790353251189),
      (0.9857491472497435, -0.02070753759799191),
      (0.7262737608867529, -0.46141463615989753),
      (1.4764017095597806, 0.5620853132271736),
      (0.6086544300013141, -0.7163047397044096),
      (1.3038230064600338, 0.38274803748825637),
      (1.0485333753688784, 0.068372783907403),
      (2.0623753302147106e-07, -22.209189752570477),
      (8.235944371252386e-07, -20.21156257872769),
      (0.000565078701137482, -10.78926056718331),
      (0.00024639347648467455, -11.986748319814511),
      (8.956754158478345, 3.1629760081916056),
      (5748.425304561833, 12.488951090034796),
    ];
    for (final (x, expected) in cases) {
      expect(log2(x), expected, reason: '$x');
    }
  });

  test('log2 : puissances de 2 exactes, cas limites', () {
    for (var k = -1070; k <= 1023; k += 7) {
      expect(log2(math.pow(2.0, k).toDouble()), k.toDouble(), reason: '2^$k');
    }
    expect(log2(0), double.negativeInfinity);
    expect(log2(-1).isNaN, isTrue);
    expect(log2(double.infinity), double.infinity);
  });
}
