List<(JournalEntry, AnalysisResult)> _results(Project p) => [for (final e in p.journal) (e, analysisResultFromJson(e.result))];

Widget _empty(BuildContext context) => Banner2(Severity.info, tr('Aucune analyse dans le journal : réalisez un calcul à l\'étape 6.', 'No analysis in the log: run a calculation in step 6.'));

/// Étape 7 : diagnostics de chaque analyse.
class DiagnosticsStep extends StatelessWidget {
  final Project p;
  const DiagnosticsStep(this.p, {super.key});
  @override
  Widget build(BuildContext context) {
    final rs = _results(p);
    return PageBody(children: [
      Heading('7. Diagnostics'),
      Text(tr('Hypothèses, diagnostics et alertes de chaque analyse. « Non évaluable » signifie que la condition dépend du plan ou du recueil et doit être justifiée par le chercheur.', 'Assumptions, diagnostics and alerts of each analysis. "Not assessable" means the condition depends on the design or data collection and must be justified by the researcher.')),
      if (rs.isEmpty) _empty(context),
      for (final (e, r) in rs)
        Card(
          child: ExpansionTile(
            initiallyExpanded: rs.length <= 2,
            leading: Icon(
              r.checks.any((c) => c.status == CheckStatus.violated) || !r.reliable ? Icons.report_outlined : Icons.fact_check_outlined,
              color: r.checks.any((c) => c.status == CheckStatus.violated) || !r.reliable ? Theme.of(context).colorScheme.error : Colors.green.shade700,
            ),
            title: Text('${e.id} — ${r.methodName}'),
            subtitle: Text(tr('${r.checks.where((c) => c.status == CheckStatus.ok).length}/${r.checks.length} conditions satisfaites · ${r.alerts.length} alerte(s)', '${r.checks.where((c) => c.status == CheckStatus.ok).length}/${r.checks.length} conditions met · ${r.alerts.length} alert(s)')),
            childrenPadding: const EdgeInsets.fromLTRB(16, 0, 16, 12),
            expandedCrossAxisAlignment: CrossAxisAlignment.start,
            children: [
              for (final c in r.checks) CheckTile(c),
              for (final a in r.alerts) Banner2(a.severity, a.message, suggestion: a.suggestion),
              if (r.checks.isEmpty && r.alerts.isEmpty) Text(tr('Aucun diagnostic spécifique pour cette méthode.', 'No specific diagnostic for this method.')),
            ],
          ),
        ),
    ]);
  }
}

/// Étape 8 : interprétation (trois questions) et grilles de rapport.
class InterpretationStep extends StatefulWidget {
  final Project p;
  const InterpretationStep(this.p, {super.key});
  @override
  State<InterpretationStep> createState() => _InterpretationStepState();
}

class _InterpretationStepState extends State<InterpretationStep> {
  @override
  Widget build(BuildContext context) {
    final rs = _results(widget.p);
    final lessons = context.read<AppState>().lessons;
    final q = widget.p.question;
    final lists = <Checklist>[
      if (q.objective == StudyObjective.predictive || rs.any((x) => x.$2.methodId.startsWith('prediction'))) ...[tripodAi, probastAi],
      if (q.dataLevel == DataLevel.aggregatedStudies || rs.any((x) => x.$2.methodId.startsWith('meta'))) prisma2020,
    ];
    return PageBody(children: [
      Heading(tr('8. Interprétation', '8. Interpretation')),
      Text(tr('Les interprétations sont des propositions générées par des gabarits déterministes à partir des résultats du moteur ; elles sont à relire et à adapter. Aucune n\'est produite par une IA générative.', 'Interpretations are proposals generated by deterministic templates from the engine results; they must be reread and adapted. None is produced by generative AI.')),
      if (rs.isEmpty) _empty(context),
      for (final (_, r) in rs)
        ResultView(r, onOpenLesson: () {
          final l = lessonById(lessons, methodInfo(r.methodId)?.lessonId ?? '');
          if (l != null) Navigator.push(context, MaterialPageRoute(builder: (_) => LessonScreen(l)));
        }),
      if (lists.isNotEmpty) ...[
        const SizedBox(height: 16),
        Heading(tr('Grilles de rapport et d\'examen critique', 'Reporting and critical appraisal grids'), style: Theme.of(context).textTheme.titleLarge),
        Text(tr('Paraphrases pédagogiques : consulter les textes officiels avant soumission. La conformité au rapport ne mesure pas la qualité méthodologique.', 'Teaching paraphrases: consult the official texts before submission. Reporting compliance does not measure methodological quality.')),
        for (final c in lists) _ChecklistCard(widget.p, c, rs.map((x) => x.$2).toList()),
      ],
    ]);
  }
}

class _ChecklistCard extends StatefulWidget {
  final Project p;
  final Checklist list;
  final List<AnalysisResult> results;
  const _ChecklistCard(this.p, this.list, this.results);
  @override
  State<_ChecklistCard> createState() => _ChecklistCardState();
}

class _ChecklistCardState extends State<_ChecklistCard> {
  Map<String, ItemAnswer> get answers => {
        for (final e in widget.p.checklistAnswers.entries)
          if (e.key.startsWith('${widget.list.id}:')) e.key.substring(widget.list.id.length + 1): ItemAnswer.values.byName(e.value)
      };

  void setAnswer(String item, ItemAnswer a) {
    setState(() => widget.p.checklistAnswers['${widget.list.id}:$item'] = a.name);
    context.read<AppState>().save(widget.p);
  }

  String? auto(ChecklistItem i) {
    final pred = widget.results.where((r) => r.methodId.startsWith('prediction')).toList();
    final meta = widget.results.where((r) => r.methodId.startsWith('meta')).toList();
    final spec = widget.p.predictionSpec;
    bool check(String id, CheckStatus s) => pred.any((r) => r.checks.any((c) => c.id == id && c.status == s));
    return switch (i.autoCheck) {
      'spec.intendedUse' => spec == null ? null : (spec.intendedUse.isEmpty ? tr('non renseigné dans l\'atelier', 'not filled in the workshop') : tr('renseigné : ${spec.intendedUse}', 'filled in: ${spec.intendedUse}')),
      'spec.targetPopulation' => spec == null ? null : (spec.targetPopulation.isEmpty ? tr('non renseignée', 'not filled in') : tr('renseignée', 'filled in')),
      'spec.horizon' => spec == null ? null : (spec.horizon.isEmpty ? tr('non renseigné', 'not filled in') : tr('horizon : ${spec.horizon}', 'horizon: ${spec.horizon}')),
      'check.sample_size' => pred.isEmpty ? null : (check('sample_size', CheckStatus.ok) ? tr('critères de Riley satisfaits', 'Riley criteria met') : tr('critères de Riley NON satisfaits', 'Riley criteria NOT met')),
      'check.missing_data' => pred.isEmpty ? null : (pred.any((r) => r.checks.any((c) => c.id == 'missing_data')) ? tr('exclusions documentées dans le résultat', 'exclusions documented in the result') : tr('aucune donnée manquante', 'no missing data')),
      'check.leakage' => pred.isEmpty ? null : tr('prédicteurs pré-spécifiés, ajustement refait à chaque réplique', 'pre-specified predictors, fit redone in each replicate'),
      'check.shrinkage' => pred.isEmpty ? null : tr('pente corrigée = ${fmt(pred.first.statistics["slope_corrected"])}', 'corrected slope = ${fmt(pred.first.statistics["slope_corrected"])}'),
      'result.calibration' || 'result.bootstrap' || 'result.corrected' || 'result.equation' => pred.isEmpty ? null : tr('présent dans le résultat', 'present in the result'),
      'result.reference' => pred.isEmpty ? null : (pred.first.statistics.containsKey('delta_auc') ? tr('comparaison réalisée', 'comparison performed') : tr('aucun modèle de référence', 'no reference model')),
      'meta.provenance' => widget.p.studies.isEmpty ? null : tr('statut et source enregistrés pour chaque valeur', 'status and source recorded for each value'),
      'meta.measure' || 'meta.model' || 'meta.forest' => meta.isEmpty ? null : tr('présent dans le résultat', 'present in the result'),
      'meta.sensitivity' => meta.isEmpty ? null : (meta.any((r) => r.figures.containsKey('leaveOneOut')) ? tr('leave-one-out réalisé', 'leave-one-out performed') : 'aucune'),
      'question.pico' => widget.p.question.population.isNotEmpty && widget.p.question.outcome.isNotEmpty ? tr('PICO renseigné (étape 1)', 'PICO filled in (step 1)') : tr('PICO incomplet', 'PICO incomplete'),
      _ => null,
    };
  }

  @override
  Widget build(BuildContext context) {
    final a = answers;
    final done = widget.list.items.where((i) => a[i.id] != null && a[i.id] != ItemAnswer.unanswered).length;
    return Card(
      child: ExpansionTile(
        title: Text(widget.list.title),
        subtitle: Text(tr('${widget.list.purpose}\n$done/${widget.list.items.length} item(s) renseigné(s) — ${widget.list.reference}', '${widget.list.purpose}\n$done/${widget.list.items.length} item(s) answered — ${widget.list.reference}')),
        childrenPadding: const EdgeInsets.fromLTRB(16, 0, 16, 12),
        children: [
          for (final i in widget.list.items)
            Padding(
              padding: const EdgeInsets.symmetric(vertical: 6),
              child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                Text('${i.id} · ${i.section}', style: Theme.of(context).textTheme.labelSmall),
                Text(i.text),
                if (auto(i) != null) Text(tr('Statoméa : ${auto(i)}', 'Statoméa: ${auto(i)}'), style: TextStyle(fontSize: 12, color: Theme.of(context).colorScheme.primary)),
                Wrap(spacing: 4, children: [
                  for (final (v, l) in [(ItemAnswer.yes, 'oui'), (ItemAnswer.partial, 'partiel'), (ItemAnswer.no, 'non'), (ItemAnswer.notApplicable, tr('sans objet', 'not applicable'))])
                    ChoiceChip(label: Text(l), selected: a[i.id] == v, onSelected: (_) => setAnswer(i.id, v), visualDensity: VisualDensity.compact),
                ]),
              ]),
            ),
        ],
      ),
    );
  }
}
